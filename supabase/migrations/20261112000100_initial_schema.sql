create type public.app_role as enum ('owner', 'advisor', 'technician');
create type public.work_order_status as enum (
  'received', 'diagnosis', 'awaiting_approval', 'awaiting_parts',
  'in_repair', 'quality_control', 'ready_for_delivery', 'delivered'
);
create type public.task_status as enum ('pending', 'in_progress', 'blocked', 'done');
create type public.estimate_status as enum ('draft', 'sent', 'partially_approved', 'approved', 'rejected', 'expired');
create type public.item_decision as enum ('pending', 'approved', 'rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role public.app_role not null default 'technician',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  phone text not null,
  email text,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.vehicles (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  plate text not null,
  make text not null,
  model text not null,
  model_year smallint check (model_year between 1900 and 2200),
  color text,
  vin text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, customer_id)
);
create unique index vehicles_plate_normalized_key
  on public.vehicles (regexp_replace(upper(plate), '[^A-Z0-9]', '', 'g'));

create table public.work_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid not null references public.customers(id) on delete restrict,
  vehicle_id uuid not null,
  opened_by uuid not null references public.profiles(id) on delete restrict,
  status public.work_order_status not null default 'received',
  odometer_km integer not null default 0 check (odometer_km >= 0),
  customer_concern text,
  target_delivery_at timestamptz,
  received_at timestamptz not null default now(),
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (vehicle_id, customer_id) references public.vehicles(id, customer_id) on delete restrict
);
create index work_orders_vehicle_created_idx on public.work_orders (vehicle_id, created_at desc);
create index work_orders_status_created_idx on public.work_orders (status, created_at desc);

create table public.intake_checklists (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null unique references public.work_orders(id) on delete cascade,
  fuel_level smallint check (fuel_level between 0 and 4),
  spare_tire_present boolean,
  tools_present boolean,
  radio_present boolean,
  upholstery_condition text,
  checklist jsonb not null default '{}'::jsonb,
  customer_signature_path text,
  signed_at timestamptz,
