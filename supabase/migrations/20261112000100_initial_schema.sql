create or replace function public.current_app_role()
returns public.app_role language sql stable security definer set search_path = '' as $$
  select p.role from public.profiles p where p.id = (select auth.uid()) and p.active = true limit 1;
$$;
create or replace function public.can_access_work_order(target_order_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.current_app_role() in ('owner', 'advisor'), false)
    or exists (select 1 from public.work_order_tasks t where t.work_order_id = target_order_id and t.assigned_to = (select auth.uid()));
$$;
create or replace function public.can_access_order_folder(object_name text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.work_orders wo
    where wo.id::text = split_part(object_name, '/', 1)
      and (public.current_app_role() in ('owner', 'advisor') or exists (
        select 1 from public.work_order_tasks t where t.work_order_id = wo.id and t.assigned_to = (select auth.uid())
      ))
  );
$$;

-- El técnico puede actualizar el avance, el cronómetro y la nota de bloqueo,
-- pero no reasignar ni cambiar el contenido de una tarea.
create or replace function public.guard_technician_task_update()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if public.current_app_role() = 'technician' and (
    new.id is distinct from old.id
    or new.work_order_id is distinct from old.work_order_id
    or new.assigned_to is distinct from old.assigned_to
    or new.title is distinct from old.title
    or new.work_type is distinct from old.work_type
    or new.created_by is distinct from old.created_by
    or new.created_at is distinct from old.created_at
  ) then
    raise exception 'El técnico solo puede actualizar el estado, los tiempos y la nota de su tarea.';
  end if;
  return new;
end;
$$;
create trigger work_order_tasks_guard_technician_update
  before update on public.work_order_tasks
  for each row execute function public.guard_technician_task_update();

